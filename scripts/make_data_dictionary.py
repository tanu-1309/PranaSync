# ruff: noqa: E702
"""Write docs/DATA_DICTIONARY.md from the code itself, so it cannot drift from the database or the parameter list.

    python scripts/make_data_dictionary.py

Covers every table in the main database, the document store, the JSON document, the 21 parameters (with units, document group and plausible limits), the units that are converted
and the files the portal writes. Run it again whenever a table or parameter changes.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from prana.data import db, docstore  # noqa: E402
from prana.risk import review  # noqa: E402
from prana.risk.params import PARAMS  # noqa: E402

PURPOSE = {
    "users": "Sign-in: one salted password hash per person (dataset patients and registered people).",
    "records": "The ready-made package for each dataset patient (JSON), rebuilt when the package version changes.",
    "accounts": "One row per person who registered themselves (name, created time). Dataset patients get a row on their first upload.",
    "profiles": "Details a person entered or corrected on the Account page (JSON). No foreign key, so dataset patients can have one.",
    "documents": "One row per uploaded file: name, size, fingerprint, kind, status. Unique per person and fingerprint, so the same file cannot be added twice.",
    "observations": "One row per value read from a document, with the line it came from. The newest value of each parameter is the person's current value.",
    "risk_snapshots": "The three risk classes after each upload, review or delete (JSON).",
    "audit_log": "Security events: sign-ins, uploads, edits, exports, administrator reads and refusals. Field names only, never the values.",
}
JSON_DOC = [
    ("doc_id, patient_id", "ids of the document and its owner", "plain"), ("version", "schema version (1)", "plain"), ("status", "needs_review or confirmed", "plain"),
    ("source", "filename, size_bytes, type, sha256, kind", "sealed"), ("uploaded_at, extracted_at, reviewed_at", "ISO times in UTC", "sealed"), ("extracted_text", "the text the values were read from (up to 200,000 characters)", "sealed"),
    ("notes", "messages from the reader (for example 'read from a picture')", "sealed"),
    ("values[]", "param, label, unit, value, original_value, text, kind, choices, min, max, source_text, observed_on, edited, ignored, read_by (patterns, AI or image)", "sealed"),
    ("edit_history[]", "at, param, label, from, to for every correction or set-aside", "sealed"), ("extraction", "method and which parameters the AI second reader added", "sealed"),
]


def main() -> int:
    out = ["# Data dictionary", "", "Generated by `python scripts/make_data_dictionary.py` from the code. Do not edit by hand.", "",
           "## Main database (SQLAlchemy; PostgreSQL in use, SQLite for tests)", ""]
    for name, t in sorted(db.metadata.tables.items()):
        out += [f"### `{name}`", "", PURPOSE.get(name, ""), "", "| Column | Type | Key / notes |", "|---|---|---|"]
        for c in t.columns:
            notes = ["primary key"] if c.primary_key else []
            notes += [f"foreign key to `{fk.column.table.name}`" for fk in c.foreign_keys]
            notes += ["required"] if not c.nullable and not c.primary_key else []
            out.append(f"| `{c.name}` | {str(c.type).split('(')[0]} | {', '.join(notes)} |")
        out.append("")
    out += ["## Document store (its own database, `DOCSTORE_URL`)", "", "One row per upload. The columns below are plain so the store can list and sort without opening anything; the JSON document is sealed (AES-256-GCM, one key per person).", "",
            "| Column | Type | Notes |", "|---|---|---|"]
    for c in docstore.store.columns:
        out.append(f"| `{c.name}` | {str(c.type).split('(')[0]} | {'sealed JSON document' if c.name == 'sealed' else 'plain'} |")
    out += ["", "### The sealed JSON document", "", "| Field | Contents | Stored |", "|---|---|---|"] + [f"| `{a}` | {b} | {c} |" for a, b, c in JSON_DOC]
    out += ["", "## The 21 parameters", "", "| Key | Name | Unit | Document group | Plausible range | Kind |", "|---|---|---|---|---|---|"]
    for k, (label, unit, group, lo, hi) in PARAMS.items():
        kind = "choice: " + ", ".join(f"{v}={n}" for v, n in review.CHOICES[k]) if k in review.CHOICES else "number"
        out.append(f"| `{k}` | {label} | {unit or '—'} | {group} | {lo:g} to {hi:g} | {kind} |")
    out += ["", "A value outside its plausible range is never stored: the reader drops it with a note.", "",
            "## Unit conversions (src/prana/risk/extract.py)", "", "| From | To | Rule |", "|---|---|---|",
            "| fasting glucose mmol/L | mg/dL | x 18.016 |", "| LDL, HDL, total cholesterol mmol/L | mg/dL | x 38.67 |", "| triglycerides mmol/L | mg/dL | x 88.57 |", "| HbA1c mmol/mol | % | x 0.09148 + 2.152 |",
            "| height cm or m, weight kg or lb | BMI kg/m2 | weight / height squared |", "| decimal comma (6,1) | decimal point (6.1) | one or two digits after the comma; three digits is a thousands separator |", "",
            "## Files the portal writes", "", "| Path | What | Sealed |", "|---|---|---|",
            "| `data/uploads/<person>/<document id>.<ext>` | the uploaded file | yes |", "| `data/documents.db` | the document store (SQLite by default) | JSON is sealed |", "| `data/.docstore_key` | the server key for sealing | no: back it up, keep it out of git |",
            "| `data/risk/training_table.csv` | the 900 practice records the risk model learned from | no |", "| `models/risk_*.txt`, `models/risk_model.json` | the trained risk model and its development check | no |",
            "| `data/knowledge/*.md`, `manifest.yaml` | the approved WHO and MedlinePlus documents and their manifest | no |", "| `results/*.json` | validation, forecast back-test and extraction evaluation | no |", ""]
    path = ROOT / "docs" / "DATA_DICTIONARY.md"
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {path} ({len(out)} lines, {len(db.metadata.tables)} tables, {len(PARAMS)} parameters)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
